/**
 * Client-half build: bundle `src/client/index.ts` into `lib/client.js`.
 *
 * The browser artifact must register itself with the GUI's module loader:
 *
 *   window.__ModuleLoader__.load({ id: '<package>', factory(require) { ... } })
 *
 * Two details of that contract are easy to get wrong, and both fail silently:
 *
 * 1. The artifact must *call the loader*. A bundle that merely runs the plugin
 *    logic mounts nothing, and the GUI reports no error — the panel is simply
 *    absent.
 * 2. Every runtime import must happen *inside* `factory(require)`. React and
 *    the Harness client packages are supplied by the loader's registry, so a
 *    static import at module scope compiles to a top-level `require("react")`
 *    with no `require` in scope, which throws "Dynamic require ... is not
 *    supported" before anything registers.
 *
 * So the module is bundled as CommonJS and then wrapped: the wrapper owns the
 * `factory`, builds a local `module`/`exports` pair, and evaluates the bundle
 * with the loader's `require` as a parameter. That is the same shape the
 * shipped plugins use.
 *
 * CSS Modules are inlined with an auto-injected `<style data-plugin>` tag.
 */
import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CSS_MODULES_PLUGIN } from './css-modules-plugin.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** The package name is the loader id; read it so the two can never drift. */
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
const PLUGIN_ID = pkg.name

const result = await build({
  entryPoints: [resolve(root, 'src/client/index.ts')],
  bundle: true,
  // CommonJS on purpose: the wrapper below supplies `require`, so every
  // import in the graph resolves through the loader's registry.
  format: 'cjs',
  platform: 'browser',
  target: ['es2022', 'chrome120'],
  sourcemap: false,
  jsx: 'automatic',
  loader: { '.css': 'css' },
  plugins: [CSS_MODULES_PLUGIN],
  define: { 'process.env.NODE_ENV': '"production"' },
  // React and the Harness client packages come from the loader, never from a
  // second copy bundled here.
  external: ['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client', '@deepseek-ai/*'],
  write: false,
})

const moduleSource = result.outputFiles[0].text

const wrapper = `// dsh-ssh-hub client half — generated by scripts/build-client.mjs, do not edit.
// Registers a lazy factory with the GUI module loader; see the build script
// for why the module body lives inside factory(require).
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PLUGIN_ID)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
    (function (module, exports, require) {
${moduleSource}
    })(module, exports, require);
    return module.exports;
  },
});
`

writeFileSync(resolve(root, 'lib/client.js'), wrapper, 'utf8')
console.log('built lib/client.js')
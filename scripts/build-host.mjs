/**
 * Host-half build: bundle `src/index.ts` into `lib/index.js`.
 *
 * The upstream package used its monorepo's shared tsdown preset; this
 * project stands alone, so it drives esbuild directly. The host half runs
 * inside the DSH host process, so every `@deepseek-ai/dsh-*` package stays
 * external — the host provides them at runtime and duplicating them here
 * would break the plugin's own service wiring.
 */
import { build } from 'esbuild'
import { rmSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

rmSync(resolve(root, 'lib'), { recursive: true, force: true })
mkdirSync(resolve(root, 'lib'), { recursive: true })

await build({
  entryPoints: [resolve(root, 'src/index.ts')],
  outfile: resolve(root, 'lib/index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: false,
  packages: 'external',
  banner: {
    js: '// dsh-ssh-hub host half — generated by scripts/build-host.mjs, do not edit.',
  },
})

console.log('built lib/index.js')
